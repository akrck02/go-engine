// Package export turns a game into a program of its own: a folder with the game's JSON and a main
// package that plays it, built for the desktop with Go or for the Nintendo 3DS with TinyGo. The
// program is built against this copy of go-engine, so what is exported plays as the editor plays.
package export

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/akrck02/go-engine/grid/game"
	"github.com/akrck02/go-engine/internal/build"
	"github.com/akrck02/go-engine/internal/notices"
)

// Target is what a game is exported for.
type Target string

const (
	Desktop     Target = "desktop"
	Nintendo3DS Target = "3ds"
)

// program is the exported program: it reads the game it embeds and plays it.
const program = `// Code generated by go-engine's export; it plays the game in game.json.
package main

import (

	"github.com/akrck02/go-engine/grid/game"
	"github.com/akrck02/go-engine/grid/player"
)

//go:embed game.json
var data []byte

func main() {
	played, err := game.Read(data)
	if err != nil {
		println(err.Error())
		return
	}
	if err := player.Run(played); err != nil {
		println(err.Error())
	}
}
`

// Result is what an export made: the program and the folder it was built in.
type Result struct {
	Program string // the built program: an executable, or a .3dsx
	Folder  string // the folder with the generated source
}

// Export writes the game's program into a folder of the target's inside a folder (made if needed):
// the program, its notices, and the source it was built from, in source.
func Export(exported *game.Game, target Target, folder string) (Result, error) {
	if err := exported.Check(); err != nil {
		return Result{}, err
	}
	source, err := build.SourceFolder()
	if err != nil {
		return Result{}, err
	}
	folder, err = filepath.Abs(filepath.Join(folder, string(target)))
	if err != nil {
		return Result{}, err
	}
	name := build.FileName(exported.Title)
	work := filepath.Join(folder, "source")
	if err := writeProgram(exported, source, work); err != nil {
		return Result{}, err
	}
	if err := build.Run(work, nil, build.GoTool(), "mod", "tidy"); err != nil {
		return Result{}, err
	}
	switch target {
	case Desktop:
		output := filepath.Join(folder, name+build.ExecutableSuffix())
		if err := build.Run(work, nil, build.GoTool(), "build", "-o", output, "."); err != nil {
			return Result{}, err
		}
		return Result{Program: output, Folder: work}, os.WriteFile(filepath.Join(folder, "THIRD_PARTY_NOTICES.md"), notices.Desktop, 0o644)
	case Nintendo3DS:
		output := filepath.Join(folder, name+".3dsx")
		tinygo, err := build.TinyGoTool()
		if err != nil {
			return Result{}, err
		}
		// TinyGo calls go itself: the same one, found or not on the path
		environment := []string{"GOFLAGS=-buildvcs=false", build.GoOnPath()}
		if err := build.Run(work, environment, tinygo, "build", "-target=nintendo3ds", "-o", output, "."); err != nil {
			return Result{}, err
		}
		return Result{Program: output, Folder: work}, os.WriteFile(filepath.Join(folder, "THIRD_PARTY_NOTICES.md"), notices.Console, 0o644)
	}
	return Result{}, fmt.Errorf("unknown target %q", target)
}

// writeProgram writes the game, the program and a go.mod that builds against go-engine's source,
// with the same versions of go-renderer and go-ui.
func writeProgram(exported *game.Game, source, work string) error {
	if err := os.MkdirAll(work, 0o755); err != nil {
		return err
	}
	data, err := exported.Marshal()
	if err != nil {
		return err
	}
	module, err := build.ModuleFile("exported/game", source)
	if err != nil {
		return err
	}
	files := map[string][]byte{
		"game.json": data,
		"main.go":   []byte(program),
		"go.mod":    []byte(module),
	}
	if sums := build.Sums(source); sums != nil {
		files["go.sum"] = sums // the same versions, so tidy need not fetch what is already known
	}
	for file, content := range files {
		if err := os.WriteFile(filepath.Join(work, file), content, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// FileName turns a game's title into a file name: lower case, words joined by dashes.
func FileName(title string) string { return build.FileName(title) }
