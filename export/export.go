// Package export turns a game into a program of its own: a folder with the game's JSON and a main
// package that plays it, built for the desktop with Go or for the Nintendo 3DS with TinyGo. The
// program is built against this copy of go-engine, so what is exported plays as the editor plays.
package export

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"

	"github.com/akrck02/go-engine/game"
)

// Target is what a game is exported for.
type Target string

const (
	Desktop     Target = "desktop"
	Nintendo3DS Target = "3ds"
)

// Notices for the software an exported program carries, to keep next to it.
//
//go:embed notices-desktop.md
var desktopNotices []byte

//go:embed notices-3ds.md
var consoleNotices []byte

// program is the exported program: it reads the game it embeds and plays it.
const program = `// Code generated by go-engine's export; it plays the game in game.json.
package main

import (
	_ "embed"

	"github.com/akrck02/go-engine/game"
	"github.com/akrck02/go-engine/player"
)

//go:embed game.json
var data []byte

func main() {
	played, err := game.Read(data)
	if err != nil {
		println(err.Error())
		return
	}
	if err := player.Run(played); err != nil {
		println(err.Error())
	}
}
`

// Result is what an export made: the program and the folder it was built in.
type Result struct {
	Program string // the built program: an executable, or a .3dsx
	Folder  string // the folder with the generated source
}

// Export writes the game's program into a folder of the target's inside a folder (made if needed):
// the program, its notices, and the source it was built from, in source.
func Export(exported *game.Game, target Target, folder string) (Result, error) {
	if err := exported.Check(); err != nil {
		return Result{}, err
	}
	source, err := sourceFolder()
	if err != nil {
		return Result{}, err
	}
	folder, err = filepath.Abs(filepath.Join(folder, string(target)))
	if err != nil {
		return Result{}, err
	}
	name := FileName(exported.Title)
	work := filepath.Join(folder, "source")
	if err := writeProgram(exported, source, work); err != nil {
		return Result{}, err
	}
	if err := run(work, nil, goTool(), "mod", "tidy"); err != nil {
		return Result{}, err
	}
	switch target {
	case Desktop:
		output := filepath.Join(folder, name+executableSuffix())
		if err := run(work, nil, goTool(), "build", "-o", output, "."); err != nil {
			return Result{}, err
		}
		return Result{Program: output, Folder: work}, os.WriteFile(filepath.Join(folder, "THIRD_PARTY_NOTICES.md"), desktopNotices, 0o644)
	case Nintendo3DS:
		output := filepath.Join(folder, name+".3dsx")
		tinygo, err := tinyGoTool()
		if err != nil {
			return Result{}, err
		}
		// TinyGo calls go itself: the same one, found or not on the path
		environment := []string{"GOFLAGS=-buildvcs=false", "PATH=" + filepath.Dir(goTool()) + string(os.PathListSeparator) + os.Getenv("PATH")}
		if err := run(work, environment, tinygo, "build", "-target=nintendo3ds", "-o", output, "."); err != nil {
			return Result{}, err
		}
		return Result{Program: output, Folder: work}, os.WriteFile(filepath.Join(folder, "THIRD_PARTY_NOTICES.md"), consoleNotices, 0o644)
	}
	return Result{}, fmt.Errorf("unknown target %q", target)
}

// writeProgram writes the game, the program and a go.mod that builds against go-engine's source,
// with the same versions of go-renderer and go-ui.
func writeProgram(exported *game.Game, source, work string) error {
	if err := os.MkdirAll(work, 0o755); err != nil {
		return err
	}
	data, err := exported.Marshal()
	if err != nil {
		return err
	}
	ownModule, err := os.ReadFile(filepath.Join(source, "go.mod"))
	if err != nil {
		return err
	}
	files := map[string][]byte{
		"game.json": data,
		"main.go":   []byte(program),
		"go.mod":    []byte(moduleFile(string(ownModule), source)),
	}
	if sums, err := os.ReadFile(filepath.Join(source, "go.sum")); err == nil {
		files["go.sum"] = sums // the same versions, so tidy need not fetch what is already known
	}
	for file, content := range files {
		if err := os.WriteFile(filepath.Join(work, file), content, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// replaceLine finds the replace directives in go-engine's own go.mod, which a program built
// against it must repeat: a module's replacements apply only to itself.
var replaceLine = regexp.MustCompile(`(?m)^replace .*$`)

// moduleFile is the exported program's go.mod.
func moduleFile(ownModule, source string) string {
	var file strings.Builder
	file.WriteString("module exported/game\n\ngo 1.25\n\nrequire github.com/akrck02/go-engine v0.0.0\n\n")
	fmt.Fprintf(&file, "replace github.com/akrck02/go-engine => %s\n", filepath.ToSlash(source))
	for _, line := range replaceLine.FindAllString(ownModule, -1) {
		file.WriteString(line + "\n")
	}
	return file.String()
}

// sourceFolder is the folder of go-engine's source, which an exported program is built against:
// where this file was when the editor was built.
func sourceFolder() (string, error) {
	_, file, _, found := runtime.Caller(0)
	if !found {
		return "", errors.New("go-engine's source cannot be found")
	}
	folder := filepath.Dir(filepath.Dir(file))
	if _, err := os.Stat(filepath.Join(folder, "go.mod")); err != nil {
		return "", fmt.Errorf("exporting needs go-engine's source, which was at %s when the editor was built", folder)
	}
	return folder, nil
}

// run runs a tool in a folder, and returns what it printed when it fails.
func run(folder string, environment []string, tool string, arguments ...string) error {
	command := exec.Command(tool, arguments...)
	command.Dir = folder
	command.Env = append(os.Environ(), environment...)
	var output bytes.Buffer
	command.Stdout, command.Stderr = &output, &output
	if err := command.Run(); err != nil {
		return fmt.Errorf("%s %s: %w\n%s", filepath.Base(tool), arguments[0], err, lastLines(output.String(), 12))
	}
	return nil
}

// lastLines keeps the end of a tool's output, where its errors are.
func lastLines(text string, count int) string {
	lines := strings.Split(strings.TrimSpace(text), "\n")
	return strings.Join(lines[max(len(lines)-count, 0):], "\n")
}

// goTool is the go command: $GO, go on the path, or the one the editor was built with.
func goTool() string {
	if tool := os.Getenv("GO"); tool != "" {
		return tool
	}
	if tool, err := exec.LookPath("go"); err == nil {
		return tool
	}
	if tool := filepath.Join(runtime.GOROOT(), "bin", "go"); fileExists(tool) {
		return tool
	}
	return "go"
}

// tinyGoTool is the TinyGo with the nintendo3ds target: $TINYGO, tinygo on the path, or in
// ~/go/bin.
func tinyGoTool() (string, error) {
	if tool := os.Getenv("TINYGO"); tool != "" {
		return tool, nil
	}
	if tool, err := exec.LookPath("tinygo"); err == nil {
		return tool, nil
	}
	if home, err := os.UserHomeDir(); err == nil {
		if tool := filepath.Join(home, "go", "bin", "tinygo"); fileExists(tool) {
			return tool, nil
		}
	}
	return "", errors.New("exporting for the 3DS needs TinyGo with the nintendo3ds target (github.com/akrck02/tinygo-3ds): set $TINYGO")
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func executableSuffix() string {
	if runtime.GOOS == "windows" {
		return ".exe"
	}
	return ""
}

// FileName turns a game's title into a file name: lower case, words joined by dashes.
func FileName(title string) string {
	var name strings.Builder
	dash := false
	for _, letter := range strings.ToLower(title) {
		switch {
		case letter >= 'a' && letter <= 'z', letter >= '0' && letter <= '9':
			if dash && name.Len() > 0 {
				name.WriteByte('-')
			}
			name.WriteRune(letter)
			dash = false
		default:
			dash = true
		}
	}
	if name.Len() == 0 {
		return "game"
	}
	return name.String()
}
